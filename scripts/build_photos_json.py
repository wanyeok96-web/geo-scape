def license_info(r):
    name = r.get("license") or ""
    urls = {
        "KOGL Type 1": "https://www.kogl.or.kr/info/licenseType1.do",
        "Public domain": "https://commons.wikimedia.org/wiki/Template:PD-South_Korea-photo-1977",
    }
    ko = {"KOGL Type 1": "공공누리 제1유형 (출처표시)", "Public domain": "퍼블릭 도메인 (보호기간 만료)"}.get(name, name)
    return {"name": name, "nameKo": ko, "url": r.get("licenseUrl") or urls.get(name, "")}


